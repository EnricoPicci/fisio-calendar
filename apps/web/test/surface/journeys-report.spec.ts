import { readFileSync, writeFileSync } from 'node:fs';
import { type JourneyResult, readResults, renderJourneysReport } from '@fisio/testkit';
import { describe, expect, it } from 'vitest';
import { resultsDir } from '../support/results';
import { specFiles } from './files';

/**
 * Renders `docs/journeys.md` from the traces the journeys of this run left (architecture §10.2,
 * §10.5), only when every journey file reported and every journey passed, so a partial or red
 * run never overwrites it. CI fails when the committed copy differs from the rendered one.
 */
const REPORT = new URL('../../../../docs/journeys.md', import.meta.url);

const INTRO = `
Generated by \`pnpm test\` from the headless journeys in \`apps/web/test/journeys\` (architecture
§10.5): each journey drives the real view-models, as the pages use them, against the real API and
auth emulator in-process, at a fixed clock. A numbered step is what the journey did (a method
call, a subscription, a clock move); the arrows list what followed, in order: requests, stream
emissions, emails. One-time codes, authenticator codes, passwords and tokens are shown as
\`<…>\`. Do not edit by hand.
`;

describe('Journey report (architecture §10.5)', () => {
  // Value: protects=docs/journeys.md documents every journey of the catalogue as it ran; fails_when=a journey file did not run or failed (the report would be partial), or the renderer drops a journey; why_new=first report (WP0.8); seam=the results directory; no_claim=the content of each trace (the journeys assert it)
  it('docs/journeys.md renders the trace of every journey, all passed', () => {
    const results = readResults<JourneyResult>(resultsDir(), 'journeys');
    const reported = new Set(results.map((result) => `test/journeys/${result.file}`));
    expect(
      specFiles('test/journeys', '.journey.spec.ts').filter((file) => !reported.has(file)),
      'journey files without a trace: run the whole web project (pnpm test)',
    ).toEqual([]);
    expect(results.filter((result) => !result.passed).map((result) => result.title)).toEqual([]);

    const report = renderJourneysReport(results, INTRO);
    for (const result of results) expect(report).toContain(`## ${result.title}`);
    let current = '';
    try {
      current = readFileSync(REPORT, 'utf8');
    } catch {
      // First rendering.
    }
    if (current !== report) writeFileSync(REPORT, report);
  });
});
