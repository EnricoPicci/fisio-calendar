// @vitest-environment jsdom
import { ClientIdSchema, type MeResponse, stringsIt as strings } from '@fisio/contracts';
import { FixedClock } from '@fisio/domain';
import { act, cleanup, render, screen } from '@testing-library/react';
import { of, Subject } from 'rxjs';
import { afterEach, describe, expect, it } from 'vitest';
import { fakeApi } from '../../test/support/fake-api';
import { fakeAuth } from '../../test/support/fake-auth';
import { fakeTokens } from '../../test/support/jwt';
import type { AuthTokens } from '../services/auth-service';
import { SessionViewModel } from '../viewmodels/SessionViewModel';
import { App } from './App';
import { DepsProvider } from './deps';

/**
 * The shell follows `page$` (architecture §7.2): loading while the session restores, the sign-in
 * page when nobody is signed in, the signed-in role's home after a sign-in.
 *
 * Generated by the ship-workflow coverage audit (Claude Fable 5.1).
 * Value: protects=App maps every SessionPage to its page and re-renders on page$;
 * fails_when=a page is mapped to the wrong component or the shell stops following page$;
 * why_new=SessionViewModel.spec proves page$, nothing renders App; seam=none;
 * no_claim=the /setup route (Playwright binding, WP0.8), restore() itself.
 */
const therapistMe: MeResponse = {
  role: 'therapist',
  therapistId: '0f1d2c3b-4a5e-4f60-8b7c-9d0e1f2a3b4c',
};
const clientMe: MeResponse = {
  role: 'client',
  clientId: ClientIdSchema.parse('6f1d2c3b-4a5e-4f60-8b7c-9d0e1f2a3b4c'),
  name: 'Giulia Bianchi',
  email: 'giulia.bianchi@fisio.test',
  locale: 'it',
};

afterEach(() => cleanup());

describe('App shell: the page the session names (architecture §7.2)', () => {
  it('loading until restore() answers, sign-in when nothing was kept, the therapist home after her sign-in', async () => {
    const auth = fakeAuth();
    const api = fakeApi();
    api.me.mockReturnValue(of(therapistMe));
    const restored = new Subject<AuthTokens | null>();
    auth.restore.mockReturnValue(restored);
    const session = new SessionViewModel(auth, new FixedClock('2027-03-01T08:00:00.000Z'));
    render(
      <DepsProvider
        deps={{ api, auth, session, strings, clock: new FixedClock('2027-03-01T08:00:00Z') }}
      >
        <App />
      </DepsProvider>,
    );
    void session.restore();

    expect(screen.getByRole('status').textContent).toBe(strings.common.loading);

    act(() => {
      restored.next(null);
      restored.complete();
    });
    expect(screen.getByRole('heading', { level: 1 }).textContent).toBe(strings.auth.title);
    expect(screen.queryByRole('status')).toBeNull();

    act(() => session.start(fakeTokens('therapist', 1_800_000_000)));
    expect(await screen.findByText(strings.home.greetingTherapist)).toBeTruthy();
    expect(screen.getByText(strings.home.therapist.title)).toBeTruthy();
    expect(screen.queryByLabelText(strings.auth.emailLabel)).toBeNull();
  });

  it('the client home after a client sign-in', async () => {
    const auth = fakeAuth();
    const api = fakeApi();
    api.me.mockReturnValue(of(clientMe));
    auth.restore.mockReturnValue(of(null));
    const session = new SessionViewModel(auth, new FixedClock('2027-03-01T08:00:00.000Z'));
    render(
      <DepsProvider
        deps={{ api, auth, session, strings, clock: new FixedClock('2027-03-01T08:00:00Z') }}
      >
        <App />
      </DepsProvider>,
    );
    await act(() => session.restore());

    act(() => session.start(fakeTokens('client', 1_800_000_000)));

    expect(await screen.findByText(strings.home.client.bookingsTitle)).toBeTruthy();
    expect(screen.queryByText(strings.home.therapist.title)).toBeNull();
  });
});
