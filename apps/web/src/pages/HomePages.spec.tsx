// @vitest-environment jsdom
import { ClientIdSchema, type MeResponse, stringsIt as strings } from '@fisio/contracts';
import { FixedClock } from '@fisio/domain';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import { of, throwError } from 'rxjs';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { type FakeApiClient, fakeApi } from '../../test/support/fake-api';
import { fakeAuth } from '../../test/support/fake-auth';
import { DepsProvider } from '../app/deps';
import { ApiError } from '../services/api-client';
import { SessionViewModel } from '../viewmodels/SessionViewModel';
import { ClientHomePage } from './ClientHomePage';
import { TherapistHomePage } from './TherapistHomePage';

/**
 * Template binding tests (architecture §10.1) for the two home placeholders: the heading follows
 * `welcome$`, `error$` is the alert, the sign-out button calls the session.
 *
 * Generated by the ship-workflow coverage audit (Claude Fable 5.1).
 * Value: protects=home templates bind welcome$/error$ and sign-out to the session;
 * fails_when=a page renders the wrong stream or the button no longer calls session.signOut();
 * why_new=HomeViewModel.spec proves the streams, nothing renders the pages; seam=none;
 * no_claim=GET /me itself (api-client.spec), greeting wording (HomeViewModel.spec).
 */
const giulia: MeResponse = {
  role: 'client',
  clientId: ClientIdSchema.parse('6f1d2c3b-4a5e-4f60-8b7c-9d0e1f2a3b4c'),
  name: 'Giulia Bianchi',
  email: 'giulia.bianchi@fisio.test',
  locale: 'it',
};

function renderHome(Page: () => React.JSX.Element, api: FakeApiClient) {
  const auth = fakeAuth();
  const session = new SessionViewModel(auth, new FixedClock('2027-03-01T08:00:00.000Z'));
  const signOut = vi.spyOn(session, 'signOut').mockResolvedValue(undefined);
  render(
    <DepsProvider
      deps={{ api, auth, session, strings, clock: new FixedClock('2027-03-01T08:00:00Z') }}
    >
      <Page />
    </DepsProvider>,
  );
  return { signOut };
}

afterEach(() => cleanup());

describe('Home page binding (architecture §7.2 placeholders, §10.1)', () => {
  it('client: the heading follows welcome$ and the sign-out button calls session.signOut()', async () => {
    const api = fakeApi();
    api.me.mockReturnValue(of(giulia));
    const { signOut } = renderHome(ClientHomePage, api);

    expect((await screen.findByRole('heading', { level: 1 })).textContent).toBe(
      `${strings.home.greeting}, ${giulia.name}`,
    );
    expect(screen.getByText(strings.home.client.noBookings)).toBeTruthy();
    expect(screen.queryByRole('alert')).toBeNull();

    fireEvent.click(screen.getByRole('button', { name: strings.common.signOut }));

    expect(signOut).toHaveBeenCalledTimes(1);
  });

  it('therapist: a refused GET /me shows error$ as the alert; the heading falls back to the plain greeting', async () => {
    const api = fakeApi();
    api.me.mockReturnValue(throwError(() => new ApiError('forbidden', 403)));
    renderHome(TherapistHomePage, api);

    expect((await screen.findByRole('alert')).textContent).toBe(strings.errors.forbidden);
    expect(screen.getByRole('heading', { level: 1 }).textContent).toBe(strings.home.greeting);
    expect(screen.getByText(strings.home.therapist.soon)).toBeTruthy();
  });
});
