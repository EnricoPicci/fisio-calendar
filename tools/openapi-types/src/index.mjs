// The one place that turns the OpenAPI document into the SPA's `paths` types. The generator CLI
// and the staleness spec in apps/web both call it, so the committed file and the check cannot
// drift from each other.
import openapiTS, { astToString } from 'openapi-typescript';

const BANNER = `// Generated by \`pnpm openapi\` from docs/openapi.json (tools/openapi-types). Do not edit:
// apps/web/src/services/api.generated.spec.ts fails while this file is out of date.
`;

/** The TypeScript source of the API types for an OpenAPI 3.1 document. */
export async function generateApiTypes(document) {
  const ast = await openapiTS(document, { alphabetize: true });
  return BANNER + astToString(ast);
}
